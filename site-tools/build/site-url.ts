// Writes SITE_URL (build/paths.ts) everywhere the site names its own origin:
// the absolute URLs in the hand-written pages (canonical, Open Graph, JSON-LD),
// robots.txt, sitemap.xml and the Canonical field of security.txt.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { generatedHeader, PAGES, SITE, SITE_URL } from './paths.js';

/** The origin the pages currently use, read from the home page's canonical URL. */
export function currentOrigin(): string {
  const home = readFileSync(join(SITE, 'index.html'), 'utf8');
  const href = /<link rel="canonical" href="([^"]+)"/.exec(home)?.[1];
  if (!href) throw new Error('index.html: no canonical URL');
  return new URL(href).origin;
}

/**
 * Points every absolute URL on `previous` at SITE_URL. Run it before the
 * generated regions are filled, so captured CLI output is never rewritten.
 */
export function rewriteOrigin(html: string, previous: string): string {
  return previous === SITE_URL ? html : html.replaceAll(previous, SITE_URL);
}

/** Public path of a page in site/, as cleanUrls serves it. */
function pagePath(page: (typeof PAGES)[number]): string {
  return page === 'index.html' ? '/' : `/${page.replace(/\.html$/, '')}`;
}

/** robots.txt, sitemap.xml and security.txt; returns the files changed. */
export function writeCrawlFiles(previous: string): number {
  const files: Record<string, string> = {
    'robots.txt': `# ${generatedHeader('SITE_URL in site-tools/build/paths.ts')}
User-agent: *
Allow: /

Sitemap: ${SITE_URL}/sitemap.xml
`,
    'sitemap.xml': `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by the site-tools build from SITE_URL in site-tools/build/paths.ts. Do not edit. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${PAGES.filter((page) => page !== '404.html')
  .map((page) => `  <url><loc>${SITE_URL}${pagePath(page)}</loc></url>`)
  .join('\n')}
</urlset>
`,
  };
  // security.txt is hand-edited (Contact, Expires); only Canonical is generated.
  const securityPath = '.well-known/security.txt';
  const security = readFileSync(join(SITE, securityPath), 'utf8');
  if (!/^Canonical: .+$/m.test(security))
    throw new Error('security.txt: no Canonical field');
  files[securityPath] = rewriteOrigin(security, previous).replace(
    /^Canonical: .+$/m,
    `Canonical: ${SITE_URL}/.well-known/security.txt`,
  );

  let changed = 0;
  for (const [name, content] of Object.entries(files)) {
    const file = join(SITE, name);
    if (readFileSync(file, 'utf8') !== content) {
      writeFileSync(file, content);
      changed += 1;
    }
  }
  return changed;
}
